import { Download, FileCheck2, ShieldCheck } from "lucide-react";
import { RequestDocument } from "../../types/models";
import {
  dataUrlToBlob,
  getBlobFromStorage,
  getCachedBlob,
} from "../../utils/fileBlobStore";
import { Modal } from "./Modal";
import { formatDateTime } from "./StatusBadge";

interface DocumentPreviewModalProps {
  open: boolean;
  onClose: () => void;
  document: RequestDocument | null;
  legalBusinessName: string;
  gstin?: string;
  pan?: string;
  bankName?: string;
  ifscCode?: string;
  onDownload: (doc: RequestDocument) => void;
}

export async function downloadKycDocument(
  doc: RequestDocument,
  legalBusinessName: string,
  extra?: { gstin?: string; pan?: string; bankName?: string; ifscCode?: string }
): Promise<void> {
  let cachedBlob =
    getCachedBlob(doc.fileName) ||
    getCachedBlob(doc.docType) ||
    getCachedBlob(`${doc.docType}_${doc.fileName}`);

  if (!cachedBlob) {
    cachedBlob =
      (await getBlobFromStorage(doc.fileName)) ||
      (await getBlobFromStorage(doc.docType)) ||
      (await getBlobFromStorage(`${doc.docType}_${doc.fileName}`));
  }

  if (!cachedBlob && doc.fileData) {
    try {
      cachedBlob = dataUrlToBlob(doc.fileData);
    } catch {
      // ignore
    }
  }

  if (cachedBlob) {
    const url = URL.createObjectURL(cachedBlob);
    const a = window.document.createElement("a");
    a.href = url;
    a.download = doc.fileName || `${doc.docType.toLowerCase()}`;
    window.document.body.appendChild(a);
    a.click();
    window.document.body.removeChild(a);
    URL.revokeObjectURL(url);
    return;
  }

  const lines = [
    "============================================================",
    "VENDORA™ (POWERED BY RUSTYSTICK TECHNOLOGIES LLP)",
    "INDIAN CORPORATE KYC & COMPLIANCE ARTIFACT SUMMARY",
    "============================================================",
    `Document Title    : ${doc.label}`,
    `Document Type     : ${doc.docType}`,
    `Legal Entity Name : ${legalBusinessName || "N/A"}`,
    `Reference Number  : ${doc.docNumber || "N/A"}`,
    extra?.gstin ? `Entity GSTIN      : ${extra.gstin}` : null,
    extra?.pan ? `Entity PAN        : ${extra.pan}` : null,
    extra?.bankName ? `Bank Name         : ${extra.bankName}` : null,
    extra?.ifscCode ? `IFSC Code         : ${extra.ifscCode}` : null,
    `Attached Filename : ${doc.fileName}`,
    `File Format       : ${doc.fileType || "application/pdf"}`,
    `File Size         : ${doc.fileSize || "420 KB"}`,
    `Uploaded At       : ${doc.uploadedAt ? formatDateTime(doc.uploadedAt) : "N/A"}`,
    "============================================================",
    "Generated by Vendora™ · Powered by RustyStick Technologies LLP",
  ]
    .filter(Boolean)
    .join("\n");

  const blob = new Blob([lines], { type: "text/plain;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = window.document.createElement("a");
  a.href = url;
  a.download = doc.fileName || `${doc.docType.toLowerCase()}.txt`;
  window.document.body.appendChild(a);
  a.click();
  window.document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

